// write writes data to root/rel (creating directories).
func (g *gen) write(rel string, data []byte) error {
	p := filepath.Join(g.root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	return os.WriteFile(p, data, 0o644)
}

func (g *gen) add(m Msg) { g.m.Messages = append(g.m.Messages, m) }

func (g *gen) source(name, kind string, failed bool) {
	g.m.Sources = append(g.m.Sources, SourceInfo{Name: name, Kind: kind, Failed: failed})
}

// mboxFile builds an mbox: messages separated by From_ lines, bodies
// quoted mboxrd-style, with LF or CRLF line endings. Offsets records where
// each message's From_ line starts (needed for .msf storeTokens).
type mboxFile struct {
	b       bytes.Buffer
	crlf    bool
	offsets []int64
}

func (f *mboxFile) add(envFrom string, envDate time.Time, raw []byte) {
	nl := "\n"
	if f.crlf {
		nl = "\r\n"
	}
	f.offsets = append(f.offsets, int64(f.b.Len()))
	fmt.Fprintf(&f.b, "From %s %s%s", envFrom, envDate.UTC().Format("Mon Jan _2 15:04:05 2006"), nl)
	for _, line := range bytes.SplitAfter(raw, []byte("\n")) {
		if len(line) == 0 {
			continue
		}
		if bytes.HasPrefix(bytes.TrimLeft(line, ">"), []byte("From ")) {
			f.b.WriteByte('>')
		}
		f.b.Write(line)
	}
	if raw := f.b.Bytes(); len(raw) > 0 && raw[len(raw)-1] != '\n' {
		f.b.WriteString(nl)
	}
	f.b.WriteString(nl)
}

// msg is a message to render as RFC 5322 text.
type msg struct {
	headers [][2]string // raw header fields, in order (values already encoded)
	body    string      // text/plain body (UTF-8) when parts is empty
	ctype   string      // Content-Type of a single-part body (default text/plain; charset=utf-8)
	cte     string      // Content-Transfer-Encoding of a single-part body
	raw     []byte      // body bytes used verbatim instead of body
	parts   []mpart     // multipart/mixed parts when non-empty
	crlf    bool
}

type mpart struct {
	headers [][2]string
	body    []byte
}

const boundary = "=_corpus_boundary_7f3a"

// bytes renders m.
func (m *msg) bytes() []byte {
	var b bytes.Buffer
	for _, h := range m.headers {
		b.WriteString(h[0] + ": " + h[1] + "\n")
	}
	switch {
	case len(m.parts) > 0:
		b.WriteString("MIME-Version: 1.0\nContent-Type: multipart/mixed; boundary=\"" + boundary + "\"\n\n")
		b.WriteString("This is a multi-part message in MIME format.\n")
		for _, p := range m.parts {
			b.WriteString("--" + boundary + "\n")
			for _, h := range p.headers {
				b.WriteString(h[0] + ": " + h[1] + "\n")
			}
			b.WriteString("\n")
			b.Write(p.body)
			if len(p.body) > 0 && p.body[len(p.body)-1] != '\n' {
				b.WriteString("\n")
			}
		}
		b.WriteString("--" + boundary + "--\n")
	default:
		ct := m.ctype
		if ct == "" {
			ct = "text/plain; charset=utf-8"
		}
		b.WriteString("MIME-Version: 1.0\nContent-Type: " + ct + "\n")
		if m.cte != "" {
			b.WriteString("Content-Transfer-Encoding: " + m.cte + "\n")
		}
		b.WriteString("\n")
		if m.raw != nil {
			b.Write(m.raw)
		} else {
			b.WriteString(m.body)
			if !strings.HasSuffix(m.body, "\n") {
				b.WriteString("\n")
			}
		}
	}
	out := b.Bytes()
	if m.crlf {
		out = bytes.ReplaceAll(out, []byte("\n"), []byte("\r\n"))
	}
	return out
}

// envelope returns the usual header fields.
func envelope(from person, to []person, subject string, date time.Time, msgID string) [][2]string {
	var tos []string
	for _, p := range to {
		tos = append(tos, p.Name+" <"+p.Email+">")
	}
	h := [][2]string{
		{"From", from.Name + " <" + from.Email + ">"},
		{"To", strings.Join(tos, ", ")},
		{"Subject", subject},
		{"Date", date.Format(time.RFC1123Z)},
	}
	if msgID != "" {
		h = append(h, [2]string{"Message-ID", "<" + msgID + ">"})
	}
	return h
}

// textPart is a text/plain part.
func textPart(body string) mpart {
	return mpart{headers: [][2]string{{"Content-Type", "text/plain; charset=utf-8"}}, body: []byte(body)}
}

// attPart is a base64 attachment part.
func attPart(name, ctype string, data []byte) mpart {
	return mpart{headers: [][2]string{
		{"Content-Type", ctype + "; name=\"" + name + "\""},
		{"Content-Disposition", "attachment; filename=\"" + name + "\""},
		{"Content-Transfer-Encoding", "base64"},
	}, body: b64(data)}
}

// b64 base64-encodes data in 76-character lines.
func b64(data []byte) []byte {
	const enc = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
	out := make([]byte, 0, len(data)*4/3+len(data)/57*2+8)
	line := 0
	for i := 0; i < len(data); i += 3 {
		var v uint32
		n := len(data) - i
		if n > 3 {
			n = 3
		}
		for j := 0; j < 3; j++ {
			v <<= 8
			if j < n {
				v |= uint32(data[i+j])
			}
		}
		chars := []byte{enc[v>>18&63], enc[v>>12&63], enc[v>>6&63], enc[v&63]}
		if n < 3 {
			chars[3] = '='
		}
		if n < 2 {
			chars[2] = '='
		}
		out = append(out, chars...)
		line += 4
		if line == 76 {
			out = append(out, '\n')
			line = 0
		}
	}
	if line > 0 {
		out = append(out, '\n')
	}
	return out
}

// blob returns n deterministic pseudo-random bytes (cheap; not from g.r so
// big sizes do not shift the rest of the corpus).
func blob(n int, seed uint64) []byte {
	out := make([]byte, n)
	x := seed*0x9E3779B97F4A7C15 + 1
	for i := range out {
		x ^= x << 13
		x ^= x >> 7
		x ^= x << 17
		out[i] = byte(x)
	}
	return out
}

func sortedCopy(s []string) []string {
	out := append([]string(nil), s...)
	sort.Strings(out)
	return out
}
