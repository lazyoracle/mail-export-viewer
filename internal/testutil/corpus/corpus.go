// Package corpus generates deterministic synthetic mail exports in every
// supported format, plus a manifest of ground truth (what the viewer must
// show for each message), for end-to-end tests, fuzz seeds and performance
// runs. It is test tooling: the product binary never imports it.
//
// Sets (Options.Sets; all by default), each under its own top directory:
//
//	gmail/        Google Takeout mbox (CRLF, X-Gmail-Labels incl. system labels)
//	thunderbird/  a profile: prefs.js tags, Local Folders and ImapMail mboxes
//	              with .msf summaries (flags, keywords), .sbd nesting
//	apple/        Apple Mail export: Name.mbox/mbox (nested), Info.plist
//	eml/          loose .eml files in nested directories
//	olm/          Outlook for Mac archives in both layouts (+ non-mail items)
//	pst/          Outlook PST files (pstgen): flags, categories, big bodies
//	              and attachments, embedded messages, RTF-only bodies
//	messy/        hostile and broken input: legacy charsets, RFC 2047/2231
//	              edge cases, broken dates and headers, truncation, garbage,
//	              duplicate ids, deep threads, thousands of labels, hostile
//	              names, HTML bombs, zip bombs, corrupt PST pages, 0-byte files
//	bulk/         Options.Bulk realistic messages for performance runs
//
// The same Options always give byte-identical output in a fresh process
// (pstgen numbers subnodes from a process-wide counter, so a second PST
// generation in the same process differs in those numbers only).
// Generated corpora are never committed.
package corpus

import (
	"bytes"
	"fmt"
	"math/rand/v2"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"github.com/lazyoracle/mail-export-viewer/internal/source"
)

// Set names.
const (
	Gmail       = "gmail"
	Thunderbird = "thunderbird"
	Apple       = "apple"
	EML         = "eml"
	OLM         = "olm"
	PST         = "pst"
	Messy       = "messy"
	Bulk        = "bulk"
)

// AllSets are the sets generated by default (Bulk only when Options.Bulk > 0).
var AllSets = []string{Gmail, Thunderbird, Apple, EML, OLM, PST, Messy}

// Options configure Generate.
type Options struct {
	Seed uint64
	// Sets limits generation to these sets; empty means AllSets (plus Bulk
	// when Bulk > 0).
	Sets []string
	// BigBytes is the size of the large attachments and bodies (default
	// 3 MiB).
	BigBytes int
	// Bulk is the number of messages in the bulk set, spread over several
	// mbox files (Gmail and Thunderbird style), one PST and one OLM.
	Bulk int
	// BulkThread is the length of one reply chain in the bulk set.
	BulkThread int
	// BulkLabels is the number of distinct Gmail labels in the bulk set.
	BulkLabels int
	// BulkFileBytes, when set, makes the first bulk mbox at least this big
	// (padding messages with filler text), for multi-GB runs.
	BulkFileBytes int64
}

// Msg is the ground truth for one message the viewer must list.
type Msg struct {
	Source    string // source name as /api/status shows it (path below the input)
	Kind      string // mbox, eml, olm, pst
	Folder    string // folder path (full, as /api/facets shows it)
	Subject   string
	MessageID string // without angle brackets; "" when the message has none
	From      string // sender address
	Date      time.Time
	Labels    []string // Gmail labels
	Cats      []string // Outlook categories
	Tags      []string // Thunderbird tag display names
	Flags     source.Flags
	Atts      []string // attachment file names, in order
	// Token is a word in the body that no other message contains ("" when
	// the body cannot be searched reliably).
	Token string
	// Thread: messages with the same non-empty Thread form exactly one
	// thread. Messages with an empty Thread are not checked.
	Thread string
	// Exact: Subject, From, Date, Flags, labels and attachments are exact
	// expectations. When false only presence (folder, count) is checked.
	Exact bool
	// Undated: the message has no usable date (Date is zero and the API
	// must report null). Only meaningful with Exact.
	Undated bool
	// FromName, when set, is the expected sender display name.
	FromName string
	// RawHas are byte strings the /raw export must contain; TextHas are
	// strings the detail text must contain.
	RawHas, TextHas []string
	// Slow marks hostile bodies (HTML bombs, huge lines): the detail must
	// still answer, within the e2e time limit.
	Slow bool
	Note string // what this message tests
}

// Search is a query with a known result.
type Search struct {
	Q        string
	Subjects []string // the exact subjects of the matches, sorted
	Deleted  string   // the deleted parameter ("" for the default)
}

// SourceInfo is an expected source.
type SourceInfo struct {
	Name, Kind string
	// Failed: the source is expected to fail or yield no messages.
	Failed bool
}

// Manifest is the ground truth of a generated corpus.
type Manifest struct {
	Root     string
	Messages []Msg
	Sources  []SourceInfo
	// TagColors maps Thunderbird tag display names to "#RRGGBB".
	TagColors map[string]string
	Searches  []Search
	// Ignored are files that must not become sources (clutter, 0-byte
	// files, unknown formats), relative to Root.
	Ignored []string
	// BigToken is in the body of each message carrying a big attachment.
	BigToken string
	// BigAttSHA256 is the hex SHA-256 of the big attachments' data
	// (BigBytes of blob(BigBytes, 99)).
	BigAttSHA256 string
	// LongThread is the Thread key of the longest reply chain, and
	// LongThreadLen its length.
	LongThread    string
	LongThreadLen int
	// CommonWord is the most frequent body word (in roughly a quarter of
	// bulk messages).
	CommonWord string
	// ManyLabels is the number of distinct labels of the many-labels case.
	ManyLabels int
	Bytes      int64
}

// gen is the generation state.
type gen struct {
	r     *rand.Rand
	o     Options
	root  string
	m     *Manifest
	vocab []string
	seq   int
	clock time.Time
	step  int // largest gap between consecutive dates, in seconds
}

// Generate writes the corpus under dir (created if needed; it should be
// empty) and returns its manifest.
func Generate(dir string, o Options) (*Manifest, error) {
	if o.BigBytes <= 0 {
		o.BigBytes = 3 << 20
	}
	root, err := filepath.Abs(dir)
	if err != nil {
		return nil, err
	}
	if err := os.MkdirAll(root, 0o755); err != nil {
		return nil, err
	}
	g := &gen{
		r:     rand.New(rand.NewPCG(o.Seed, o.Seed^0x9e3779b97f4a7c15)),
		o:     o,
		root:  root,
		m:     &Manifest{Root: root, TagColors: map[string]string{}, BigToken: "qzbigattachment"},
		clock: time.Date(2012, 1, 2, 9, 0, 0, 0, time.UTC),
	}
	// Dates advance by up to a day (about 12 years for 10k messages);
	// bulk corpora spread theirs over about 15 years.
	g.step = 86400
	if n := o.Bulk + o.BulkThread; n > 10000 {
		g.step = max(60, int(15*365*86400/int64(n))*2)
	}
	g.vocab = vocabulary(g.r)
	g.m.CommonWord = g.vocab[0]
	sets := o.Sets
	if len(sets) == 0 {
		sets = append([]string(nil), AllSets...)
		if o.Bulk > 0 {
			sets = append(sets, Bulk)
		}
	}
	fns := map[string]func() error{
		Gmail: g.gmail, Thunderbird: g.thunderbird, Apple: g.apple, EML: g.eml,
		OLM: g.olm, PST: g.pst, Messy: g.messy, Bulk: g.bulk,
	}
	for _, s := range sets {
		fn, ok := fns[s]
		if !ok {
			return nil, fmt.Errorf("corpus: unknown set %q", s)
		}
		if err := fn(); err != nil {
			return nil, fmt.Errorf("corpus: %s: %w", s, err)
		}
	}
	sort.Slice(g.m.Sources, func(i, j int) bool { return g.m.Sources[i].Name < g.m.Sources[j].Name })
	err = filepath.Walk(root, func(_ string, fi os.FileInfo, err error) error {
		if err == nil && fi.Mode().IsRegular() {
			g.m.Bytes += fi.Size()
		}
		return err
	})
	return g.m, err
}

// --- helpers ---------------------------------------------------------------

// token returns a fresh unique body word. All tokens have the same length,
// so a prefix search for one never matches another.
func (g *gen) token() string {
	g.seq++
	return fmt.Sprintf("qzt%07d", g.seq)
}

// date returns the next message date (strictly increasing, whole seconds).
func (g *gen) date() time.Time {
	g.clock = g.clock.Add(time.Duration(1+g.r.IntN(g.step)) * time.Second)
	return g.clock
}

// vocabulary builds pseudo-words from consonant-vowel syllables (no q, x
// or z, so they never collide with tokens or fixed search words).
func vocabulary(r *rand.Rand) []string {
	cons := "bcdfghjklmnprstvw"
	vows := "aeiou"
	seen := map[string]bool{}
	var out []string
	for len(out) < 3000 {
		n := 2 + r.IntN(3)
		var b strings.Builder
		for i := 0; i < n; i++ {
			b.WriteByte(cons[r.IntN(len(cons))])
			b.WriteByte(vows[r.IntN(len(vows))])
		}
		if w := b.String(); !seen[w] {
			seen[w] = true
			out = append(out, w)
		}
	}
	return out
}

// words returns n random vocabulary words separated by spaces, with a line
// break every ~12 words.
func (g *gen) words(n int) string {
	var b strings.Builder
	for i := 0; i < n; i++ {
		if i > 0 {
			if i%12 == 0 {
				b.WriteByte('\n')
			} else {
				b.WriteByte(' ')
			}
		}
		// Skewed choice: frequent words are frequent.
		k := int(float64(len(g.vocab)) * g.r.Float64() * g.r.Float64())
		b.WriteString(g.vocab[k])
	}
	return b.String()
}

