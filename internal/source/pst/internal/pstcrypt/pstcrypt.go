var mpbbI = func() (inv [256]byte) {
	for i, v := range mpbbR {
		inv[v] = byte(i)
	}
	return inv
}()

// Permute encodes (encode true) or decodes b in place with
// NDB_CRYPT_PERMUTE.
func Permute(b []byte, encode bool) {
	t := &mpbbI
	if encode {
		t = &mpbbR
	}
	for i, c := range b {
		b[i] = t[c]
	}
}

// Cyclic encodes or decodes (the operation is its own inverse) b in place
// with NDB_CRYPT_CYCLIC; key is the low 32 bits of the block's BID.
func Cyclic(b []byte, key uint32) {
	w := uint16(key ^ key>>16)
	for i, c := range b {
		c += byte(w)
		c = mpbbR[c]
		c += byte(w >> 8)
		c = mpbbS[c]
		c -= byte(w >> 8)
		c = mpbbI[c]
		c -= byte(w)
		b[i] = c
		w++
	}
}
